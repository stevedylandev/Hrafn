/// Namespace URIs used by the XML and framing layers. Extension namespaces live
/// with the modules that implement them.
public enum Namespaces {
    public static let stream = "http://etherx.jabber.org/streams"
    public static let client = "jabber:client"
    public static let server = "jabber:server"
    public static let component = "jabber:component:accept"
    public static let streamErrors = "urn:ietf:params:xml:ns:xmpp-streams"
    public static let stanzas = "urn:ietf:params:xml:ns:xmpp-stanzas"
    public static let tls = "urn:ietf:params:xml:ns:xmpp-tls"
    public static let sasl = "urn:ietf:params:xml:ns:xmpp-sasl"
    public static let bind = "urn:ietf:params:xml:ns:xmpp-bind"
    public static let session = "urn:ietf:params:xml:ns:xmpp-session"
    public static let xml = "http://www.w3.org/XML/1998/namespace"
}
